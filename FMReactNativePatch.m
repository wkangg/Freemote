#import "FMReactNativePatch.h"

// Run in the React Native screen's JS before its bundle (see the RCTInstance hook). Twitch's EmotePart draws
// every chat emote as a square of its height; our emote IDs say how wide ours are, and this gives them that width.
// Chat rows also add our emotes to messages that came in before their channel's emotes did, and keep deleted messages,
// dimmed.
NSString *const FMReactNativePatchSource =
    @"(function () {\n"
    @"  // Error level, since release builds drop anything lower. Native logs these as its own (see watchForReactNativeReady).\n"
    @"  function log(message) {\n"
    @"    try {\n"
    @"      globalThis.nativeLoggingHook('[Freemote] ' + message, 3);\n"
    @"    } catch (e) {}\n"
    @"  }\n"
    @"\n"
    @"  // freemote_<emote ID>_<width per 100 of height>, for an emote that isn't square\n"
    @"  function aspectRatio(emoteID) {\n"
    @"    var match = typeof emoteID === 'string' && /^freemote_[A-Za-z0-9]+_([0-9]+)$/.exec(emoteID);\n"
    @"    return match ? Number(match[1]) / 100 : 0;\n"
    @"  }\n"
    @"\n"
    @"  function styleHeight(style) {\n"
    @"    if (Array.isArray(style)) {\n"
    @"      var height;\n"
    @"      for (var i = 0; i < style.length; i++) {\n"
    @"        var styleHeightAt = styleHeight(style[i]);\n"
    @"        if (styleHeightAt !== undefined)\n"
    @"          height = styleHeightAt;\n"
    @"      }\n"
    @"      return height;\n"
    @"    }\n"
    @"    return style && typeof style === 'object' && typeof style.height === 'number' ? style.height : undefined;\n"
    @"  }\n"
    @"\n"
    @"  // ReactNative: react-native's index, whose exports are getters (View is read when a row needs it)\n"
    @"  var React, ReactNative, patchedEmotePart = false, patchedChatMessageRow = false, loggedError = false;\n"
    @"\n"
    @"  // EmotePart draws an emote as an image (chat-emote-<id>) in a box (chat-emote-wrapper-<id>), both a square of the\n"
    @"  // emote's height. Ours get their own width.\n"
    @"  function widen(element, ratio) {\n"
    @"    if (!element || typeof element !== 'object' || !element.props)\n"
    @"      return element;\n"
    @"    var props = element.props, changes = null;\n"
    @"    var testID = typeof props.testID === 'string' ? props.testID : '';\n"
    @"    var height = styleHeight(props.style);\n"
    @"    if (testID.indexOf('chat-emote-') === 0 && height !== undefined)\n"
    @"      changes = {style: [props.style, {width: Math.max(1, Math.round(height * ratio))}]};\n"
    @"\n"
    @"    var children = props.children, newChildren = children, changed = false;\n"
    @"    if (Array.isArray(children)) {\n"
    @"      newChildren = children.map(function (child) {\n"
    @"        var newChild = widen(child, ratio);\n"
    @"        changed = changed || newChild !== child;\n"
    @"        return newChild;\n"
    @"      });\n"
    @"    } else {\n"
    @"      newChildren = widen(children, ratio);\n"
    @"      changed = newChildren !== children;\n"
    @"    }\n"
    @"    if (changed) {\n"
    @"      changes = changes || {};\n"
    @"      changes.children = newChildren;\n"
    @"    }\n"
    @"    return changes ? React.cloneElement(element, changes) : element;\n"
    @"  }\n"
    @"\n"
    @"  function patchEmotePart(exports) {\n"
    @"    var EmotePart = exports.EmotePart;\n"
    @"    exports.EmotePart = function FreemoteEmotePart(props) {\n"
    @"      // Always called, since it uses hooks\n"
    @"      var element = EmotePart.apply(this, arguments);\n"
    @"      var ratio = aspectRatio(props && props.emoteId);\n"
    @"      if (!ratio)\n"
    @"        return element;\n"
    @"      try {\n"
    @"        return widen(element, ratio);\n"
    @"      } catch (e) {\n"
    @"        if (!loggedError)\n"
    @"          log(\"Couldn't size a React Native emote: \" + e);\n"
    @"        loggedError = true;\n"
    @"        return element;\n"
    @"      }\n"
    @"    };\n"
    @"    log('Patched React Native emote sizes');\n"
    @"  }\n"
    @"\n"
    @"  // Messages that came in before their channel's emotes loaded are drawn without them, so native sends each channel's\n"
    @"  // emote names here as they load (see sendEmoteTable in Tweak.x), and chat rows add the ones their message is missing.\n"
    @"  var emoteTables = new Map(); // channel ID -> Map(name -> our emote ID)\n"
    @"  var tableListeners = new Map(); // channel ID -> Set(listener)\n"
    @"  var loggedMissingTable = false;\n"
    @"\n"
    @"  function setEmotes(channelID, names) {\n"
    @"    var table = new Map();\n"
    @"    for (var name in names) {\n"
    @"      if (Object.prototype.hasOwnProperty.call(names, name) && typeof names[name] === 'string')\n"
    @"        table.set(name, names[name]);\n"
    @"    }\n"
    @"    channelID = String(channelID);\n"
    @"    emoteTables.set(channelID, table);\n"
    @"    var listeners = tableListeners.get(channelID);\n"
    @"    if (listeners)\n"
    @"      listeners.forEach(function (listener) {\n"
    @"        listener();\n"
    @"      });\n"
    @"  }\n"
    @"\n"
    @"  // Same as isInvisibleCharacter in Tweak.x: these at either end of a word don't keep it from matching\n"
    @"  function isInvisible(c) {\n"
    @"    return c < 0x20 || (c >= 0x7F && c <= 0x9F) || c === 0xA0 || c === 0xAD || c === 0x034F || c === 0x115F || c === 0x1160 || c === 0x1680 || c === 0x180E\n"
    @"      || (c >= 0x2000 && c <= 0x200F) || c === 0x2028 || c === 0x2029 || c === 0x202F || (c >= 0x205F && c <= 0x2064)\n"
    @"      || c === 0x2800 || c === 0x3000 || c === 0x3164 || (c >= 0xFE00 && c <= 0xFE0F) || c === 0xFEFF || (c >= 0xE0000 && c <= 0xE007F);\n"
    @"  }\n"
    @"\n"
    @"  // A message's emotes are {id, start, end} in code points of its body, end included, like the IRC emotes tag.\n"
    @"  // Returns them plus ours in words they don't cover yet, or null if there are none to add.\n"
    @"  function emotesWithOurs(body, emotes, table) {\n"
    @"    var chars = Array.from(body), taken = [], added = [];\n"
    @"    if (Array.isArray(emotes)) {\n"
    @"      emotes.forEach(function (emote) {\n"
    @"        if (emote && typeof emote.start === 'number' && typeof emote.end === 'number')\n"
    @"          for (var i = Math.max(0, emote.start); i <= emote.end && i < chars.length; i++)\n"
    @"            taken[i] = true;\n"
    @"      });\n"
    @"    }\n"
    @"    var wordStart = 0;\n"
    @"    for (var i = 0; i <= chars.length; i++) {\n"
    @"      if (i < chars.length && chars[i] !== ' ')\n"
    @"        continue;\n"
    @"      var start = wordStart, end = i;\n"
    @"      wordStart = i + 1;\n"
    @"      var id = table.get(chars.slice(start, end).join(''));\n"
    @"      if (id === undefined) {\n"
    @"        var trimmed = false;\n"
    @"        for (; start < end && isInvisible(chars[start].codePointAt(0)); start++)\n"
    @"          trimmed = true;\n"
    @"        for (; end > start && isInvisible(chars[end - 1].codePointAt(0)); end--)\n"
    @"          trimmed = true;\n"
    @"        if (trimmed && start < end)\n"
    @"          id = table.get(chars.slice(start, end).join(''));\n"
    @"      }\n"
    @"      if (id === undefined)\n"
    @"        continue;\n"
    @"      var free = true;\n"
    @"      for (var j = start; j < end && free; j++)\n"
    @"        free = !taken[j];\n"
    @"      if (free)\n"
    @"        added.push({id: id, start: start, end: end - 1});\n"
    @"    }\n"
    @"    return added.length ? (Array.isArray(emotes) ? emotes : []).concat(added) : null;\n"
    @"  }\n"
    @"\n"
    @"  // The message with our emotes added, or the same message if it has them all. Kept per message and table, so a row's\n"
    @"  // message only changes when the table does.\n"
    @"  var messagesWithOurEmotes = new WeakMap();\n"
    @"  function messageWithOurEmotes(message, table) {\n"
    @"    if (!table || !message || typeof message !== 'object' || typeof message.body !== 'string')\n"
    @"      return message;\n"
    @"    var cached = messagesWithOurEmotes.get(message);\n"
    @"    if (cached && cached.table === table)\n"
    @"      return cached.message;\n"
    @"    var emotes = emotesWithOurs(message.body, message.emotes, table), result = message;\n"
    @"    if (emotes) {\n"
    @"      result = Object.assign(Object.create(Object.getPrototypeOf(message)), message);\n"
    @"      result.emotes = emotes;\n"
    @"    }\n"
    @"    messagesWithOurEmotes.set(message, {table: table, message: result});\n"
    @"    return result;\n"
    @"  }\n"
    @"\n"
    @"  // A message deleted by a moderator (CLEARMSG, or a timeout or ban of its sender) gets deleted: true, and the row\n"
    @"  // draws 'message deleted by a moderator.' instead of it. It's kept and dimmed instead, like Chatterino and 7TV.\n"
    @"  // A moderator's DETAILED view (deleted with a modActionType) already shows it, struck through, so that's only dimmed.\n"
    @"  // Native sets freemoteKeepDeletedMessages from Freemote's settings.\n"
    @"  var loggedDeleted = false, loggedNoView = false;\n"
    @"\n"
    @"  // Messages in the chat history that were deleted before you opened chat. Native leaves them in the history as\n"
    @"  // ordinary messages (the chat drops the ones marked deleted) and sends their IDs here, so their rows are dimmed too.\n"
    @"  var deletedHistoryIDs = new Set();\n"
    @"  function setDeletedHistoryMessages(ids) {\n"
    @"    if (!Array.isArray(ids))\n"
    @"      return;\n"
    @"    if (deletedHistoryIDs.size > 5000)\n"
    @"      deletedHistoryIDs.clear();\n"
    @"    ids.forEach(function (id) {\n"
    @"      deletedHistoryIDs.add(String(id));\n"
    @"    });\n"
    @"    // Rows that were drawn first\n"
    @"    tableListeners.forEach(function (listeners) {\n"
    @"      listeners.forEach(function (listener) {\n"
    @"        listener();\n"
    @"      });\n"
    @"    });\n"
    @"  }\n"
    @"  function deletedRowView() {\n"
    @"    var View = ReactNative && ReactNative.View;\n"
    @"    if (!View && !loggedNoView) {\n"
    @"      loggedNoView = true;\n"
    @"      log(\"No React Native View, deleted messages stay deleted\");\n"
    @"    }\n"
    @"    return View;\n"
    @"  }\n"
    @"\n"
    @"  function keptMessage(message) {\n"
    @"    if (message.modActionType)\n"
    @"      return message;\n"
    @"    var kept = Object.assign(Object.create(Object.getPrototypeOf(message)), message);\n"
    @"    kept.deleted = false;\n"
    @"    // At the end, so emote positions don't move\n"
    @"    var tag = typeof kept.body === 'string' ? removalTag(kept) : null;\n"
    @"    if (tag)\n"
    @"      kept.body = kept.body + ' ' + tag;\n"
    @"    return kept;\n"
    @"  }\n"
    @"\n"
    @"  // ChatMessageRow is React.memo(ChatMessageRowComponent), with props {message: {body, emotes, ...}, channelID, ...}\n"
    @"  function patchChatMessageRow(exports) {\n"
    @"    var ChatMessageRow = exports.ChatMessageRow;\n"
    @"    function FreemoteChatMessageRow(props) {\n"
    @"      var channelID = props && props.channelID != null ? String(props.channelID) : null;\n"
    @"      var table = channelID ? emoteTables.get(channelID) : undefined;\n"
    @"      var forceUpdate = React.useReducer(function (n) {\n"
    @"        return n + 1;\n"
    @"      }, 0)[1];\n"
    @"      React.useEffect(function () {\n"
    @"        if (!channelID)\n"
    @"          return undefined;\n"
    @"        var listeners = tableListeners.get(channelID);\n"
    @"        if (!listeners)\n"
    @"          tableListeners.set(channelID, listeners = new Set());\n"
    @"        listeners.add(forceUpdate);\n"
    @"        // A table that came in between drawing the row and now\n"
    @"        if (emoteTables.get(channelID) !== table)\n"
    @"          forceUpdate();\n"
    @"        return function () {\n"
    @"          listeners.delete(forceUpdate);\n"
    @"        };\n"
    @"      }, [channelID]);\n"
    @"\n"
    @"      if (!table && emoteTables.size && !loggedMissingTable) {\n"
    @"        loggedMissingTable = true;\n"
    @"        log('Chat row for channel ' + channelID + \" has no emote table (have \" + Array.from(emoteTables.keys()).join(', ') + ')');\n"
    @"      }\n"
    @"      var message = props && props.message, newMessage = message, DeletedView = null;\n"
    @"      try {\n"
    @"        newMessage = messageWithOurEmotes(message, table);\n"
    @"      } catch (e) {\n"
    @"        if (!loggedError)\n"
    @"          log(\"Couldn't add emotes to a React Native chat row: \" + e);\n"
    @"        loggedError = true;\n"
    @"      }\n"
    @"      try {\n"
    @"        var deletedInHistory = newMessage && typeof newMessage === 'object' && newMessage.id != null && deletedHistoryIDs.has(String(newMessage.id));\n"
    @"        if (newMessage && typeof newMessage === 'object' && (newMessage.deleted || deletedInHistory) && globalThis.freemoteKeepDeletedMessages !== false && (DeletedView = deletedRowView())) {\n"
    @"          if (newMessage.deleted)\n"
    @"            newMessage = keptMessage(newMessage);\n"
    @"          if (!loggedDeleted)\n"
    @"            log('Kept a deleted message');\n"
    @"          loggedDeleted = true;\n"
    @"        }\n"
    @"      } catch (e) {\n"
    @"        DeletedView = null;\n"
    @"        if (!loggedError)\n"
    @"          log(\"Couldn't keep a deleted React Native chat message: \" + e);\n"
    @"        loggedError = true;\n"
    @"      }\n"
    @"      var row = React.createElement(ChatMessageRow, newMessage === message ? props : Object.assign({}, props, {message: newMessage}));\n"
    @"      return DeletedView ? React.createElement(DeletedView, {style: {opacity: 0.45}, testID: 'freemote-deleted-message'}, row) : row;\n"
    @"    }\n"
    @"    exports.ChatMessageRow = React.memo(FreemoteChatMessageRow);\n"
    @"    log('Patched React Native chat rows');\n"
    @"  }\n"
    @"\n"
    @"  // A /clear (CLEARCHAT without a user) gets the chat store to empty its lines, unless you're a moderator, and then add\n"
    @"  // Twitch's 'chat cleared' line. While the store handles one, the set call that empties the lines is left out, so chat\n"
    @"  // stays like it does for moderators, and Twitch's line is still added. The store gets these events through\n"
    @"  // LibraryTmiClient's onModeration, and its set from zustand's createStore.\n"
    @"  var patchedTmiClient = false, patchedStore = false, handlingClear = false, loggedClear = false;\n"
    @"\n"
    @"  // Timeouts and bans by login, and messages deleted one at a time, so a kept message can say why it was removed\n"
    @"  var removals = new Map(), deletedIDs = new Set();\n"
    @"\n"
    @"  function noteRemoval(event) {\n"
    @"    if (event.kind === 'delete' && event.targetMsgId) {\n"
    @"      if (deletedIDs.size > 5000)\n"
    @"        deletedIDs.clear();\n"
    @"      deletedIDs.add(String(event.targetMsgId));\n"
    @"    } else if ((event.kind === 'timeout' || event.kind === 'ban') && event.userLogin) {\n"
    @"      if (removals.size > 5000)\n"
    @"        removals.clear();\n"
    @"      // The server's time, like the messages' tmiSentTs, so the phone's clock doesn't matter\n"
    @"      removals.set(String(event.userLogin).toLowerCase(), {kind: event.kind, durationSeconds: Number(event.durationSeconds), at: Number(event.sentTs) || Date.now()});\n"
    @"    }\n"
    @"  }\n"
    @"\n"
    @"  // Same as durationText in Tweak.x: '10 minutes', in the largest unit it's a whole number of\n"
    @"  function durationText(seconds) {\n"
    @"    var units = [[86400, 'day'], [3600, 'hour'], [60, 'minute'], [1, 'second']];\n"
    @"    for (var i = 0; i < units.length; i++) {\n"
    @"      if (seconds % units[i][0] === 0) {\n"
    @"        var count = seconds / units[i][0];\n"
    @"        return count + ' ' + units[i][1] + (count === 1 ? '' : 's');\n"
    @"      }\n"
    @"    }\n"
    @"    return seconds + ' seconds';\n"
    @"  }\n"
    @"\n"
    @"  // '(timed out for 10 minutes)' or '(banned)' for a message its sender's timeout or ban removed\n"
    @"  function removalTag(message) {\n"
    @"    if (message.id != null && deletedIDs.has(String(message.id)))\n"
    @"      return null;\n"
    @"    var removal = typeof message.user === 'string' ? removals.get(message.user.toLowerCase()) : undefined;\n"
    @"    if (!removal || (typeof message.tmiSentTs === 'number' && message.tmiSentTs > removal.at + 5000))\n"
    @"      return null;\n"
    @"    if (removal.kind === 'ban')\n"
    @"      return '(banned)';\n"
    @"    return removal.durationSeconds > 0 ? '(timed out for ' + durationText(removal.durationSeconds) + ')' : '(timed out)';\n"
    @"  }\n"
    @"\n"
    @"  function patchTmiClient(Client) {\n"
    @"    var onModeration = Client.prototype.onModeration;\n"
    @"    Client.prototype.onModeration = function (listener) {\n"
    @"      if (typeof listener !== 'function')\n"
    @"        return onModeration.apply(this, arguments);\n"
    @"      return onModeration.call(this, function (event) {\n"
    @"        // Before Twitch marks the messages, so their rows have it when they're drawn again\n"
    @"        try {\n"
    @"          if (event)\n"
    @"            noteRemoval(event);\n"
    @"        } catch (e) {}\n"
    @"        if (!event || event.kind !== 'clear' || globalThis.freemoteKeepDeletedMessages === false)\n"
    @"          return listener.apply(this, arguments);\n"
    @"        handlingClear = true;\n"
    @"        try {\n"
    @"          return listener.apply(this, arguments);\n"
    @"        } finally {\n"
    @"          handlingClear = false;\n"
    @"        }\n"
    @"      });\n"
    @"    };\n"
    @"    log('Patched React Native chat clears');\n"
    @"  }\n"
    @"\n"
    @"  function setKeepingLines(set) {\n"
    @"    return function (partial) {\n"
    @"      if (!handlingClear || !partial || typeof partial !== 'object' || !Array.isArray(partial.lines) || partial.lines.length)\n"
    @"        return set.apply(this, arguments);\n"
    @"      if (!loggedClear)\n"
    @"        log('Kept chat through a /clear');\n"
    @"      loggedClear = true;\n"
    @"      var kept = Object.assign({}, partial);\n"
    @"      delete kept.lines;\n"
    @"      delete kept.pausedWindow;\n"
    @"      if (!Object.keys(kept).length)\n"
    @"        return undefined;\n"
    @"      var args = Array.prototype.slice.call(arguments);\n"
    @"      args[0] = kept;\n"
    @"      return set.apply(this, args);\n"
    @"    };\n"
    @"  }\n"
    @"\n"
    @"  // Recent messages that come in after Twitch's chat history was handed over (see addLateRecentMessages in Tweak.x) go\n"
    @"  // in above the chat's lines through its own prependHistory, made into lines by Twitch's toHistoryLines like its own\n"
    @"  // history. prependHistory leaves out lines the chat already has, only fills it up to its limit and applies deletions,\n"
    @"  // but only runs once per chat (historyLoaded), so while they go in, the store's get says it hasn't.\n"
    @"  var toHistoryLines = null, searchedHistoryLines = false;\n"
    @"  var chatStores = []; // {get, set, prependHistory, adding, channel}, newest last\n"
    @"  var pendingHistory = new Map(); // channel -> {data, at}, for a chat that hasn't put in its own history yet\n"
    @"\n"
    @"  function channelKey(channel) {\n"
    @"    return typeof channel === 'string' && channel ? channel.replace(/^#/, '').toLowerCase() : null;\n"
    @"  }\n"
    @"\n"
    @"  // From its own history, or else any of its lines\n"
    @"  function storeChannel(store) {\n"
    @"    if (store.channel)\n"
    @"      return store.channel;\n"
    @"    var lines = (store.get() || {}).lines;\n"
    @"    for (var i = 0; Array.isArray(lines) && i < lines.length; i++) {\n"
    @"      var channel = lines[i] && lines[i].line ? channelKey(lines[i].line.channel) : null;\n"
    @"      if (channel)\n"
    @"        return channel;\n"
    @"    }\n"
    @"    return null;\n"
    @"  }\n"
    @"\n"
    @"  function addHistoryToStore(store, channel, data) {\n"
    @"    var state = store.get(), count = state.historyMessageCount;\n"
    @"    var before = Array.isArray(state.lines) ? state.lines.length : 0;\n"
    @"    var lines = toHistoryLines(data, channel, false);\n"
    @"    store.adding = true;\n"
    @"    try {\n"
    @"      store.prependHistory(lines);\n"
    @"    } finally {\n"
    @"      store.adding = false;\n"
    @"    }\n"
    @"    var after = store.get().lines, added = Math.max(0, (Array.isArray(after) ? after.length : 0) - before);\n"
    @"    // It counts only the lines it just added\n"
    @"    store.set({historyMessageCount: (typeof count === 'number' ? count : 0) + added});\n"
    @"    log('Added ' + added + ' of ' + (Array.isArray(lines) ? lines.length : 0) + ' late recent messages to the chat history of ' + channel);\n"
    @"  }\n"
    @"\n"
    @"  function addHistory(channel, data) {\n"
    @"    try {\n"
    @"      channel = channelKey(channel);\n"
    @"      if (!channel || !data)\n"
    @"        return;\n"
    @"      if (!toHistoryLines) {\n"
    @"        log('No toHistoryLines, late recent messages for ' + channel + ' are left out');\n"
    @"        return;\n"
    @"      }\n"
    @"      for (var i = chatStores.length - 1; i >= 0; i--) {\n"
    @"        var storeKey = storeChannel(chatStores[i]);\n"
    @"        // A newer chat whose channel isn't known yet is likely this one, not an older chat of the same channel\n"
    @"        if (!storeKey)\n"
    @"          break;\n"
    @"        if (storeKey !== channel)\n"
    @"          continue;\n"
    @"        if (chatStores[i].get().historyLoaded) {\n"
    @"          addHistoryToStore(chatStores[i], channel, data);\n"
    @"          return;\n"
    @"        }\n"
    @"        break;\n"
    @"      }\n"
    @"      // Its chat puts in its own history first\n"
    @"      if (pendingHistory.size > 10)\n"
    @"        pendingHistory.clear();\n"
    @"      // A chat with no history and no lines never says its channel, so it doesn't get them\n"
    @"      pendingHistory.set(channel, {data: data, at: Date.now()});\n"
    @"      log('Late recent messages for ' + channel + ' wait for its chat history');\n"
    @"    } catch (e) {\n"
    @"      log(\"Couldn't add late recent messages: \" + e);\n"
    @"    }\n"
    @"  }\n"
    @"\n"
    @"  // The chat store, whose state has prependHistory. holder is what its get looks at, and becomes the store.\n"
    @"  function wrapChatStore(state, set, get, holder) {\n"
    @"    var store = holder;\n"
    @"    store.get = get;\n"
    @"    store.set = set;\n"
    @"    store.prependHistory = state.prependHistory;\n"
    @"    store.channel = null;\n"
    @"    state.prependHistory = function (lines) {\n"
    @"      var result = store.prependHistory.apply(this, arguments);\n"
    @"      try {\n"
    @"        var channel = Array.isArray(lines) && lines.length && lines[0] ? channelKey(lines[0].channel) : null;\n"
    @"        if (channel)\n"
    @"          store.channel = channel;\n"
    @"        channel = storeChannel(store);\n"
    @"        var pending = channel && pendingHistory.get(channel);\n"
    @"        if (pending && get().historyLoaded) {\n"
    @"          pendingHistory.delete(channel);\n"
    @"          // Not from an earlier visit to the channel\n"
    @"          if (Date.now() - pending.at < 30000)\n"
    @"            addHistoryToStore(store, channel, pending.data);\n"
    @"          else\n"
